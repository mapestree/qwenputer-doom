"""Rasterize a Doom map into the raycaster's grid (firmware/map.h).
   python3 -I tools/wad2grid.py WAD MAP CELL OUT.h [--show]
Each cell centre is located in a sector (nearest linedef hit by a +x ray, and which side of it the point is on).
Cells are flood-filled from the player start with Doom's movement limits (step up <= 24, headroom >= 56; doors and
lifts pass). Unreached cells become walls. Cells behind the exit switch (special 11) become 'X'.
Kept: the floor plan. Dropped: heights, light, textures, things (monsters, items), damaging floors."""
import sys
from collections import deque
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
import wad

DOOR = {1, 26, 27, 28, 31, 32, 33, 34, 117, 118}  # manual doors (open on use)
LIFT = {62, 88, 10, 21, 120, 121, 122, 123}
EXIT = {11, 51, 52, 124}


def main():
    path, name, cell, out = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4]
    verts, lines, sides, sectors, things = wad.read_map(path, name)
    xs = [v[0] for v in verts]; ys = [v[1] for v in verts]
    x0, y1 = min(xs), max(ys)
    mw, mh = (max(xs) - x0) // cell + 3, (y1 - min(ys)) // cell + 3  # one cell of border all round
    ox, oy = x0 - cell, y1 + cell  # grid (0,0) corner, Doom coordinates (y up; grid rows go down)
    seg = [(verts[l.v1], verts[l.v2], l) for l in lines]

    def sector_at(px, py):
        best, hit = None, None
        for (ax, ay), (bx, by), l in seg:
            if (ay > py) == (by > py):
                continue
            t = (py - ay) / (by - ay); x = ax + t * (bx - ax)
            if x > px and (best is None or x < best):
                best, hit = x, (ax, ay, bx, by, l)
        if hit is None:
            return None
        ax, ay, bx, by, l = hit
        right = (bx - ax) * (py - ay) - (by - ay) * (px - ax) < 0  # right of v1->v2 = front side
        sd = l.right if right else l.left
        return None if sd == 0xFFFF else sides[sd].sector

    centre = lambda c, r: (ox + c * cell + cell / 2, oy - r * cell - cell / 2)
    sec = [[sector_at(*centre(c, r)) for c in range(mw)] for r in range(mh)]
    door_secs = {sides[l.left].sector for l in lines if l.special in DOOR and l.left != 0xFFFF}
    lift_secs = {s for l in lines if l.special in LIFT for s, t in enumerate(sectors) if t.tag == l.tag and l.tag}

    def ok(a, b):  # can the player walk from sector a to sector b
        A, B = sectors[a], sectors[b]
        if b in door_secs or a in door_secs:
            return True
        if B.floor - A.floor > 24 and b not in lift_secs and a not in lift_secs:
            return False
        return B.ceil - max(A.floor, B.floor) >= 56 or b in lift_secs

    p = next(t for t in things if t.type == 1)
    sc, sr = int((p.x - ox) // cell), int((oy - p.y) // cell)
    seen = [[False] * mw for _ in range(mh)]
    seen[sr][sc] = True; q = deque([(sc, sr)])
    while q:
        c, r = q.popleft()
        for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nc, nr = c + dc, r + dr
            if 0 <= nc < mw and 0 <= nr < mh and not seen[nr][nc] and sec[nr][nc] is not None \
                    and ok(sec[r][c], sec[nr][nc]):
                seen[nr][nc] = True; q.append((nc, nr))
    g = [["." if seen[r][c] else "#" for c in range(mw)] for r in range(mh)]
    for r in range(mh):
        for c in range(mw):
            if seen[r][c] and sec[r][c] in door_secs:
                g[r][c] = "D"
    for (ax, ay), (bx, by), l in seg:  # exit switch: wall cells just behind it, floor cells in front
        if l.special not in EXIT:
            continue
        n = max(abs(bx - ax), abs(by - ay)) // 4 + 1
        nx, ny = (by - ay), -(bx - ax); d = (nx * nx + ny * ny) ** 0.5; nx, ny = nx / d, ny / d  # right normal
        for i in range(n + 1):
            x, y = ax + (bx - ax) * i / n, ay + (by - ay) * i / n
            c, r = int((x + nx * cell * 0.5 - ox) // cell), int((oy - (y + ny * cell * 0.5)) // cell)
            if g[r][c] == ".":
                g[r][c] = "E"
    for r in range(mh):  # the switch's alcove can be thinner than a cell: walls touching the exit floor show it
        for c in range(mw):
            if g[r][c] == "#" and any(g[r + dr][c + dc] == "E" for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1))
                                      if 0 <= r + dr < mh and 0 <= c + dc < mw):
                g[r][c] = "X"
    g[sr][sc] = "P"
    ang = round(-p.angle * 256 / 360) % 256  # Doom: CCW degrees, y up; ours: 256 units, clockwise on screen
    rows = ["".join(row) for row in g]
    if "--show" in sys.argv:
        print("\n".join(rows))
    hdr = [f"// Generated by tools/wad2grid.py from {Path(path).name} {name}, {cell} map units per cell. Do not edit.",
           f"#define MW {mw}", f"#define MH {mh}", f"#define START_ANG {ang}", f"#define START_C {sc}", f"#define START_R {sr}",
           f"static const char MAP[MH][MW + 1] = {{"] + [f'    "{r}",' for r in rows] + ["};"]
    Path(out).write_text("\n".join(hdr) + "\n")
    print(f"{name}: {mw}x{mh} cells ({mw * mh} B), floor {sum(r.count('.') for r in rows)}, "
          f"doors {sum(r.count('D') for r in rows)}, exit {sum(r.count('X') for r in rows)}/"
          f"{sum(r.count('E') for r in rows)}, start ({sc},{sr}) ang {ang}", file=sys.stderr)


main()
