// A turn-based ASCII raycaster for the chipformer RV32 machine, driven through the P3 bridge like calc:
// each run (GO, after </tool_call>) reads the tool call's first parameter from the text buffer as keys,
// moves the player, prints one frame inside <tool_response>, and parks (exit ecall) until the next call.
//   keys: w/s forward/back, a/d turn left/right, q/e strafe left/right (several per call, e.g. "wwd")
// Fixed point 16.16 throughout; RAM keeps the player between runs. Build: toolchain/rvcc.
#include "rt.h"

#ifndef W
#define W 40  // frame columns (one ray each)
#endif
#ifndef H
#define H 12  // frame rows
#endif
#define FIX 16
#define ONE (1 << FIX)
#define NANG 256  // angle units per turn
#define TURN 8    // a/d: 8/256 of a turn (11.25 degrees)
#define STEP (ONE / 2)  // per half-step; w/s/q/e take two (one cell)
#define TEXT ((const volatile unsigned char *)0x8000)
#define ROWS 80
enum { TOOL_RESPONSE = 256, TOOL_RESPONSE_END };

#ifdef MAPH
#include MAPH  // generated by tools/wad2grid.py: MW, MH, START_ANG, MAP; '#' wall, 'X' exit switch, '.' floor,
               // 'D' door (always open), 'E' in front of the exit switch, 'P' start
#else
#define MW 24
#define MH 16
#define START_ANG 0
#define START_C 1
#define START_R 1
static const char MAP[MH][MW + 1] = {  // small test map
    "########################",
    "#P.....#...............#",
    "#......#...............#",
    "#......#....#####......#",
    "#..............#.......#",
    "#......#.......#.......#",
    "####.###.......#####.###",
    "#......#...........#...#",
    "#......#...........#...#",
    "#..##..#####.#######...#",
    "#..##..................#",
    "#......#######.#########",
    "#......#.......#.......#",
    "###.####.......#...EEEX#",
    "#..............#...EEEX#",
    "########################",
};
#endif
#ifndef WALLH
#define WALLH 2  // wall height in cells (E1M1 at 32 units/cell: walls are mostly 128+ units)
#endif

// sin of a * 2pi / 256, 16.16, a = 0..63 (a quarter); the rest by symmetry
static const int SINQ[65] = {
    0, 1608, 3216, 4821, 6424, 8022, 9616, 11204, 12785, 14359, 15924, 17479, 19024, 20557, 22078, 23586,
    25080, 26558, 28020, 29466, 30893, 32303, 33692, 35062, 36410, 37736, 39040, 40320, 41576, 42806, 44011,
    45190, 46341, 47464, 48559, 49624, 50660, 51665, 52639, 53581, 54491, 55368, 56212, 57022, 57798, 58538,
    59244, 59914, 60547, 61145, 61705, 62228, 62714, 63162, 63572, 63944, 64277, 64571, 64827, 65043, 65220,
    65358, 65457, 65516, 65536,
};
static int fsin(int a) {
    a &= NANG - 1;
    if (a < 64) return SINQ[a];
    if (a < 128) return SINQ[128 - a];
    if (a < 192) return -SINQ[a - 128];
    return -SINQ[256 - a];
}
static int fcos(int a) { return fsin(a + 64); }
static int mul(int a, int b) { return (int)(((long long)a * b) >> FIX); }

static int px, py, ang;  // player position (16.16 cells) and heading
static int started, won;
static char keys[64];

static int cell(int x, int y) { return x < 0 || y < 0 || x >= MW || y >= MH ? '#' : MAP[y][x]; }
static int solid(int c) { return c == '#' || c == 'X'; }

static void put(int c) { rv_ecall2(1, c, 0, 0); }
static void puts_(const char *s) { while (*s) put(*s++); }

static int gather(void) {  // as calc.c: the first parameter's value (after the 2nd '>' up to the next '<')
    int n = 0, gt = 0, i;
    for (i = 1; i <= ROWS; i++) {
        const volatile unsigned char *r = TEXT + 16 * i;
        int c = r[0];
        if (!c) break;
        for (int k = 0; k < 16 && c; c = ++k < 16 ? r[k] : 0) {
            if (gt < 2) gt += c == '>';
            else if (c == '<') { keys[n] = 0; return n; }
            else if (c != '\n' && n < (int)sizeof keys - 1) keys[n++] = (char)c;
        }
    }
    keys[n] = 0;
    return n;
}

static void try_move(int dx, int dy) {  // axis-separated, so the player slides along walls
    int nx = px + dx, ny = py + dy, m = ONE * 2 / 5;  // keep 0.4 cells from walls
    int ox = dx > 0 ? m : -m, oy = dy > 0 ? m : -m;
    if (!solid(cell((nx + ox) >> FIX, py >> FIX))) px = nx;
    if (!solid(cell(px >> FIX, (ny + oy) >> FIX))) py = ny;
}

static void act(void) {
    for (const char *k = keys; *k; k++) {
        int dx = mul(fcos(ang), STEP), dy = mul(fsin(ang), STEP);
        switch (*k | 32) {  // lower-case
        case 'w': try_move(dx, dy); try_move(dx, dy); break;
        case 's': try_move(-dx, -dy); try_move(-dx, -dy); break;
        case 'q': try_move(dy, -dx); try_move(dy, -dx); break;
        case 'e': try_move(-dy, dx); try_move(-dy, dx); break;
        case 'a': ang -= TURN; break;
        case 'd': ang += TURN; break;
        }
        if (cell(px >> FIX, py >> FIX) == 'E') won = 1;
    }
}

static unsigned char col_h[W], col_c[W];

static void cast(void) {
    int dx = fcos(ang), dy = fsin(ang);
    int plx = -mul(dy, 43690), ply = mul(dx, 43690);  // camera plane: ~66 degree field of view
    for (int x = 0; x < W; x++) {
        int cam = (2 * x + 1) * ONE / W - ONE;
        int rx = dx + mul(plx, cam), ry = dy + mul(ply, cam);
        int mx = px >> FIX, my = py >> FIX;
        int arx = rx < 0 ? -rx : rx, ary = ry < 0 ? -ry : ry;
        // |1/ray| in 16.16: 2^32 / |r| without a 64-bit divide
        int ddx = arx >> 2 ? (1 << 30) / (arx >> 2) : 1 << 28;
        int ddy = ary >> 2 ? (1 << 30) / (ary >> 2) : 1 << 28;
        int sx = rx < 0 ? -1 : 1, sy = ry < 0 ? -1 : 1;
        int fx = px & (ONE - 1), fy = py & (ONE - 1);
        int tx = mul(rx < 0 ? fx : ONE - fx, ddx), ty = mul(ry < 0 ? fy : ONE - fy, ddy);
        int side = 0, c = '#';
        for (int n = 0; n < MW + MH; n++) {
            if (tx < ty) { tx += ddx; mx += sx; side = 0; }
            else { ty += ddy; my += sy; side = 1; }
            c = cell(mx, my);
            if (solid(c)) break;
        }
        int d = side ? ty - ddy : tx - ddx;  // perpendicular distance, 16.16
        if (d < ONE / 8) d = ONE / 8;
        int h = (WALLH * H << FIX) / d;
        col_h[x] = h > H ? H : h;
        // shade by distance (cells): near walls dense, far walls light; y-facing walls one step lighter
        static const char ramp[] = "@#%*+=-:";
        int s = (d >> FIX) + 2 * side;  // cells
        s = s < 2 ? 0 : s < 4 ? 1 : s < 7 ? 2 : s < 11 ? 3 : s < 16 ? 4 : s < 24 ? 5 : s < 36 ? 6 : 7;
        col_c[x] = c == 'X' ? 'X' : ramp[s];
    }
}

static void draw(void) {
    for (int y = 0; y < H; y++) {
        int dy2 = 2 * y - (H - 1);  // row's offset from the horizon, in half-rows
        int ady = dy2 < 0 ? -dy2 : dy2;
        int end = W;
        while (end > 0 && dy2 < 0 && ady >= col_h[end - 1]) end--;  // drop trailing ceiling spaces
        for (int x = 0; x < end; x++)
            put(ady < col_h[x] ? col_c[x] : dy2 < 0 ? ' ' : ady > H / 2 ? '.' : ',');
        put('\n');
    }
}

static void init(void) {
    px = (START_C << FIX) + ONE / 2;
    py = (START_R << FIX) + ONE / 2;
    ang = START_ANG;
    started = 1;
}

int main(void) {
    for (;;) {
        rv_ecall2(93, 0, 0, 0);  // park: HALT; the next GO resumes here
        if (!started) init();
        if (gather() > 0 && !won) act();
        put('\n');
        put(TOOL_RESPONSE);
        put('\n');
        if (won) puts_("EXIT REACHED - level complete\n");
        cast();
        draw();
        put(TOOL_RESPONSE_END);
        put('\n');
    }
}
